#!/usr/bin/env node
// Generates WCAG.md from wcag/snapshot.json (W3C) + src/wcag-map.mjs + widget settings.
// test/wcag.test.js fails if WCAG.md is out of date: run npm run wcag:report.
import {readFile, writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {map, WCAG_VERSION} from '../src/wcag-map.mjs';
import {SETTINGS} from '../src/widget.js';

const understanding = id => `https://www.w3.org/WAI/WCAG22/Understanding/${id}.html`;

export async function report() {
  const snapshot = JSON.parse(await readFile(new URL('../wcag/snapshot.json', import.meta.url), 'utf8'));
  const rows = snapshot.criteria.filter(c => !c.obsolete && (c.level !== 'AAA' || map[c.num]));
  const count = s => rows.filter(c => c.level !== 'AAA' && map[c.num]?.status === s).length;
  const modes = Object.fromEntries(rows.map(c => [c.num, SETTINGS.filter(s => s.wcag.includes(c.num)).map(s => s.label)]));
  const lines = [
    '# WCAG coverage',
    '',
    `Generated by \`npm run wcag:report\` from W3C's official WCAG ${WCAG_VERSION} data (${snapshot.source}, fetched ${snapshot.fetched}) and \`src/wcag-map.mjs\`. Do not edit by hand.`,
    '',
    `Level A and AA: **${count('framework')} met by the framework**, **${count('supports')} supported** (the framework gives the tool, the author applies it), **${count('author')} author responsibility**. Obsolete criteria (such as 4.1.1 Parsing) are left out.`,
    '',
    'Using this framework does not make a site conformant. Conformance depends on the whole page, its content and its behaviour.',
    '',
    '| Criterion | Level | Status | Widget setting | How |',
    '|---|---|---|---|---|',
    ...rows.map(c => `| [${c.num} ${c.handle}](${understanding(c.id)}) | ${c.level} | ${map[c.num].status} | ${modes[c.num].join(', ') || '—'} | ${map[c.num].how.replaceAll('|', '\\|')} |`),
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(new URL('../WCAG.md', import.meta.url), await report());
  console.log('WCAG.md written');
}
